test('end-of-game feedback is private, persistent and linked to the exact match',async({page,review},testInfo)=>{
  const {readFile,readdir}=await import('node:fs/promises');
  const server=await isolatedServer(testInfo,c=>{small(c);c.match_defaults.objective.rules.victory_rule.points=1;},()=>{},['--coordinator']);review.afterClose(server.stop);
  await page.goto(server.url);await page.getByRole('button',{name:'Play Against Bot',exact:true}).click();await revision(page,0);
  await page.locator('#commit').click();await revision(page,1);
  await expect(page.getByRole('dialog',{name:'Game complete'})).toBeVisible();
  await expect(page.locator('#outcome-banner strong')).toContainText('LOSS');
  await expect(page.locator('#outcome-banner > div')).toContainText('At the final tick');
  const match=await page.evaluate(()=>window.atemporal.net.matchId),id=new URL(page.url()).pathname.split('/')[2];
  await page.getByRole('button',{name:'Give feedback',exact:true}).click();
  const message='I liked changing the timeline. <script>This stays private.</script>';
  await page.getByLabel('Message to the creator',{exact:true}).fill(message);
  await review.capture('feedback-form',page);
  await page.getByRole('button',{name:'Send feedback',exact:true}).click();
  await expect(page.locator('#feedback-status')).toContainText('has been saved');
  await page.setViewportSize({width:1366,height:768});await review.capture('feedback-saved-1366',page);
  const folder=`${server.dir}/games/${id}/replays/${match}/feedback`;
  const files=await readdir(folder);expect(files).toHaveLength(1);
  const record=JSON.parse(await readFile(`${folder}/${files[0]}`,'utf8'));
  expect(record.message).toBe(message);expect(record.game_id).toBe(id);expect(record.match_id).toBe(match);
  expect(record.username).toBe('Player');expect(record.log_path).toBe(`${id}/replays/${match}`);
  const endpoint=`${server.url}api/games/${id}/feedback`;
  const body={match_id:match,submission_id:record.submission_id,message,revision:1};
  expect((await page.request.post(endpoint,{data:body})).ok()).toBe(true);
  expect(await readdir(folder)).toHaveLength(1);
  expect((await page.request.post(endpoint,{data:{...body,match_id:'../outside'}})).status()).toBe(400);
  expect((await page.request.post(endpoint,{data:{...body,message:' '}})).status()).toBe(400);
  expect((await page.request.post(endpoint,{data:{...body,message:'a'.repeat(5001)}})).status()).toBe(400);
  expect((await page.request.get(`${server.url}games/${id}/replays/${match}/feedback/${files[0]}`)).status()).toBe(404);
  const directory=await(await page.request.get(server.url+'api/directory')).text();expect(directory).not.toContain(message);
  await page.goto(server.url);await server.stop();await server.start();
  expect(JSON.parse(await readFile(`${folder}/${files[0]}`,'utf8'))).toEqual(record);
  expect((await page.request.post(endpoint,{data:body})).ok()).toBe(true);expect(await readdir(folder)).toHaveLength(1);
});
